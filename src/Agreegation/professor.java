package Agreegation;

public class professor {

	private String name;
	private String sub;
	
	public professor(String name, String sub) {
		this.name = name;
		this.sub = sub;
	}
	
	public void setName(String name) {
		this.name = name;
	}
	
	public String getName() {
		return name;
	}
	
	public void setSub(String sub) {
		this.sub = sub;
	}
	
	public String getSub() {
		return sub;
	}
	
	}
